"use strict";
// Renders the documentation that is GENERATED from the setting registry (configRegistry.js):
// the three tables of ARCHITECTURE.md ("Environment variables") and the whole of .env.example.
// `npm run docs:env` (scripts/gen-env-docs.js) writes them; test/unit/envInventory.test.js fails
// when the committed files differ from what this renders. Pure: no file access here.

const { REGISTRY } = require("./configRegistry");

const SECTIONS = [
  ["required", "REQUIRED"],
  ["basics", "BASICS (optional)"],
  ["addresses", "ADDRESSES (optional)"],
  ["firstadmin", "FIRST ADMIN (optional)"],
  ["email", "EMAIL (optional locally, needed in production)"],
  ["safety", "ADMIN SESSIONS / SAFETY (optional)"],
  ["ai", "AI (optional; photo scan, descriptions, price check)"],
  ["lookup", "BOOK LOOKUP (optional)"],
  ["helloasso", "HELLOASSO (optional; membership only)"],
  ["dev", "DEVELOPER SCRIPTS (optional)"],
];

const cell = (s) => String(s == null ? "" : s).replace(/\|/g, "\\|").replace(/\n/g, " ");
const yesNo = (b) => (b ? "yes" : "no");

function requiredTable() {
  const rows = REGISTRY.filter((s) => s.required);
  return [
    "| Variable | Secret? | Where set | What it does |",
    "|---|---|---|---|",
    ...rows.map((s) => `| \`${s.name}\` | ${yesNo(s.secret)} | ${cell(s.whereText)} | ${cell(s.doc)} |`),
  ].join("\n");
}

function optionalTable() {
  const rows = REGISTRY.filter((s) => !s.required && s.scope !== "workflow");
  return [
    "| Variable | Secret? | Default | Where set | What it does |",
    "|---|---|---|---|---|",
    ...rows.map((s) => `| \`${s.name}\` | ${yesNo(s.secret)} | ${cell(s.defaultText)} | ${cell(s.whereText)} | ${cell(s.doc)} |`),
  ].join("\n");
}

function githubTable() {
  const rows = REGISTRY.filter((s) => s.github);
  const kind = (g) => (g.kind === "secret" ? "GitHub secret" : "GitHub repository variable");
  return [
    "| Name | Kind | Used by | What it is |",
    "|---|---|---|---|",
    ...rows.map((s) => `| \`${s.name}\` | ${kind(s.github)} | ${cell(s.github.usedBy)} | ${cell(s.github.doc)} |`),
  ].join("\n");
}

const BLOCKS = { "env-required": requiredTable, "env-optional": optionalTable, "env-github": githubTable };
const marker = (id, edge) =>
  edge === "start"
    ? `<!-- ${id}:start (GENERATED by \`npm run docs:env\` from src/lib/configRegistry.js: edit the registry, not this table) -->`
    : `<!-- ${id}:end -->`;

// Replaces the text between each pair of markers; throws when a marker is missing.
function applyToArchitecture(text) {
  let out = text;
  for (const [id, render] of Object.entries(BLOCKS)) {
    const s = out.indexOf(`<!-- ${id}:start`);
    const e = out.indexOf(marker(id, "end"));
    if (s < 0 || e < 0 || e < s) throw new Error(`ARCHITECTURE.md is missing the ${id} markers (<!-- ${id}:start ... --> and ${marker(id, "end")})`);
    out = `${out.slice(0, s)}${marker(id, "start")}\n${render()}\n${out.slice(e)}`;
  }
  return out;
}

// ---- .env.example -----------------------------------------------------------------------------
const plain = (s) => String(s).replace(/\*\*/g, "").replace(/`/g, "").replace(/\[([^\]]+)\]\([^)]*\)/g, "$1");
function hint(spec) {
  let first = plain(spec.doc).split(/(?<=\.)\s/)[0].trim();
  if (!first.endsWith(".")) first += ".";
  const def = plain(spec.defaultText || "");
  if (def && !/^none/i.test(def) && spec.defaultText !== undefined && !spec.required) first += ` Default: ${def}.`;
  return first;
}
function wrap(text, width = 96) {
  const words = text.split(" ");
  const lines = [];
  let line = "";
  for (const w of words) {
    if (line && line.length + 1 + w.length > width) { lines.push(line); line = w; } else line = line ? `${line} ${w}` : w;
  }
  if (line) lines.push(line);
  return lines;
}

function renderEnvExample() {
  const out = [
    "# GENERATED FILE: edit src/lib/configRegistry.js, then run `npm run docs:env`. A test fails if this file is stale.",
    "#",
    "# Copy to .env for local development. On Render the same names are real env vars (see render.yaml;",
    "# DATABASE_URL is set BY HAND in the dashboard).",
    "#",
    "# This file lists EVERY variable the code reads; the full table (defaults, secret or not, where each is",
    '# set in production) is in ARCHITECTURE.md, "Environment variables".',
    "#",
    '# REQUIRED lines are uncommented. OPTIONAL lines are commented out: remove the leading "# " to use one.',
    "# Values here are placeholders, never real secrets.",
  ];
  for (const [id, title] of SECTIONS) {
    const specs = REGISTRY.filter((s) => s.section === id && s.example !== undefined);
    if (!specs.length) continue;
    out.push("", `# ${"-".repeat(Math.max(4, 64 - title.length))} ${title}`);
    for (const s of specs) {
      for (const l of wrap(s.hint || hint(s))) out.push(`# ${l}`);
      out.push(`${s.active ? "" : "# "}${s.name}=${s.example}`);
    }
  }
  const skipped = REGISTRY.filter((s) => s.exampleSkip).map((s) => s.name);
  out.push("", `# Not listed above on purpose: ${skipped.join(", ")} (see ARCHITECTURE.md for each).`, "");
  return out.join("\n");
}

module.exports = { applyToArchitecture, renderEnvExample, requiredTable, optionalTable, githubTable, marker, BLOCKS, SECTIONS };
