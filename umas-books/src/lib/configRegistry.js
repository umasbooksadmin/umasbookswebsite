// THE declared list of every setting (environment variable) the app, its scripts and its
// GitHub workflows use. One entry per variable, and this file is the single source for:
//   - the accessors in config.js (kind, default and the variable's own parsing rule),
//   - the tables in ARCHITECTURE.md and the whole of .env.example (`npm run docs:env`
//     regenerates them; test/unit/envInventory.test.js fails when they are stale),
//   - the launch validation in env.js (`required`, `group`).
//
// Entry fields
//   name        the variable
//   kind        "string" | "int" | "ms" (a number; "ms" only says it is a duration) | "flag" (on/off)
//   scope       "app" (read by src/), "script" (read only by scripts/ or a tool), "workflow" (GitHub Actions only)
//   section     where it is grouped in .env.example (see SECTIONS in configDocs.js); none = not listed there
//   default     the value used when unset: a value, or (env) => value. Strings: "unset or empty -> default"
//   secret      true = never logged, never quoted in a message; secrets must be kind "string"
//   required    true = the boot fails (in production) without it
//   group       an OPTIONAL_GROUPS id (GROUPS below): the feature that turns itself off if any is missing
//   where       "render" | "github-variable" | "github-secret" | "both" (Render AND GitHub) | "render-auto"
//               (Render sets it) | "local" | "tests" | "ci" | "code" (set by the code itself)
//   whereText / defaultText / doc   the words of the ARCHITECTURE.md table ("Where set", "Default", "What it does")
//   hint        the comment above its line in .env.example (default: the first sentence of doc)
//   example / active   the line in .env.example (active = uncommented); exampleSkip = why it is not listed there
//   github      { kind: "secret"|"variable", usedBy, doc }: also listed in the GitHub Actions table
//   ownWarning  its module already logs a line for a bad value (db.js, app.js): config.warnInvalid skips it
//
// Parsing rules (int / ms / flag) are per variable on purpose: each keeps EXACTLY the rule its
// own parser had before this registry existed (blank / trim / digits / integer / finite / min /
// max / parse / zeroIsDefault / lenient / words / onWords / offWords). Do not "tidy" one entry to
// match another: test/unit/configEquivalence.test.js pins every rule against the original parser.
